/**
 * Embed the reader template into the builder as a TS module, so export can
 * run fully client-side with no server.
 *
 *   node scripts/embed-template.mjs
 *
 * Walks template/ (source only, no node_modules/.next/lockfile), replaces
 * content/book.json + content/source.json with placeholder markers, and
 * writes builder/export/generated-template.ts (committed).
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const TEMPLATE_DIR = join(ROOT, "template");
const OUT = join(ROOT, "builder/export/generated-template.ts");

const SKIP_DIRS = new Set(["node_modules", ".next", ".git"]);
const SKIP_FILES = new Set(["package-lock.json", "next-env.d.ts", "tsconfig.tsbuildinfo", ".env", ".env.local", ".DS_Store"]);
const PLACEHOLDERS = {
  "content/book.json": "__BOOKLITH_BOOK_JSON__",
  "content/source.json": "__BOOKLITH_SOURCE_JSON__",
};

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (SKIP_DIRS.has(name)) continue;
    const st = statSync(full);
    if (st.isDirectory()) out.push(...walk(full));
    else if (!SKIP_FILES.has(name)) out.push(full);
  }
  return out;
}

const files = {};
for (const full of walk(TEMPLATE_DIR)) {
  const rel = relative(TEMPLATE_DIR, full);
  let content = readFileSync(full, "utf8");
  if (rel === "package.json") {
    // strip workspace-private fields; rename for the exported app
    const pkg = JSON.parse(content);
    delete pkg.devDependencies?.["@types/react"]; // keep; harmless
    content = JSON.stringify(pkg, null, 2);
  }
  if (PLACEHOLDERS[rel]) content = PLACEHOLDERS[rel];
  files[rel] = content;
}

const ts =
  "// AUTO-GENERATED by scripts/embed-template.mjs — do not edit by hand.\n" +
  "// Source of truth: /template. Regenerate with `npm run embed-template`.\n" +
  "export const TEMPLATE_FILES: Record<string, string> = " +
  JSON.stringify(files, null, 2) +
  ";\n";

writeFileSync(OUT, ts);
console.log(`✔ embedded ${Object.keys(files).length} template files -> ${relative(ROOT, OUT)}`);
